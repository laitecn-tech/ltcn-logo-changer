"""Validate and convert uploads into a complete, immutable set of icons."""

from __future__ import annotations

from hashlib import sha256
from io import BytesIO
import os
from pathlib import Path
import re
import shutil
import tempfile
import unicodedata

from PIL import Image, ImageOps, UnidentifiedImageError

from .const import (
    ASSET_FILES,
    ASSET_FORMAT_VERSION,
    MAX_IMAGE_PIXELS,
    MAX_IMAGE_SIDE,
    MAX_UPLOAD_BYTES,
)

_REVISION = re.compile(r"[0-9a-f]{32}\Z")


class ImageValidationError(ValueError):
    """A translated, user-actionable upload error."""

    def __init__(self, code: str) -> None:
        super().__init__(code)
        self.code = code


def validate_name(value: object) -> str:
    """Accept plain Unicode names, never markup or control characters."""
    if not isinstance(value, str):
        raise ImageValidationError("invalid_name")
    name = value.strip()
    if (
        not 1 <= len(name) <= 64
        or any(unicodedata.category(char).startswith("C") for char in name)
        or "<" in name
        or ">" in name
    ):
        raise ImageValidationError("invalid_name")
    return name


def valid_revision(value: object) -> bool:
    """Keep all paths integration-owned, even if stored options are malformed."""
    return isinstance(value, str) and bool(_REVISION.fullmatch(value))


def assets_exist(root: Path, revision: object) -> bool:
    """An incomplete icon set must never become the active brand."""
    return valid_revision(revision) and all(
        (root / str(revision) / filename).is_file() for filename in ASSET_FILES
    )


def _decode(raw: bytes) -> Image.Image:
    if not raw:
        raise ImageValidationError("invalid_image")
    if len(raw) > MAX_UPLOAD_BYTES:
        raise ImageValidationError("image_too_large")
    try:
        with Image.open(BytesIO(raw)) as image:
            if image.format not in {"PNG", "JPEG", "WEBP", "ICO"}:
                raise ImageValidationError("unsupported_image")
            width, height = image.size
            if (
                min(width, height) < 16
                or max(width, height) > MAX_IMAGE_SIDE
                or width * height > MAX_IMAGE_PIXELS
            ):
                raise ImageValidationError("invalid_dimensions")
            if getattr(image, "is_animated", False):
                raise ImageValidationError("animated_image")
            image.load()
            return ImageOps.exif_transpose(image).convert("RGBA")
    except ImageValidationError:
        raise
    except (UnidentifiedImageError, OSError, ValueError, Image.DecompressionBombError) as exc:
        raise ImageValidationError("invalid_image") from exc


def _square(image: Image.Image, size: int) -> Image.Image:
    resized = ImageOps.contain(image, (size, size), Image.Resampling.LANCZOS)
    canvas = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    canvas.alpha_composite(
        resized, ((size - resized.width) // 2, (size - resized.height) // 2)
    )
    return canvas


def convert_icon(source: Path, root: Path) -> str:
    """Generate all sizes before publishing the revision directory.

    Run in HA's executor. No original file, EXIF, uploaded filename or user path
    is published. A failed conversion leaves previous revisions untouched.
    """
    with source.open("rb") as stream:
        raw = stream.read(MAX_UPLOAD_BYTES + 1)
    image = _decode(raw)
    revision = sha256(ASSET_FORMAT_VERSION.encode() + b"\0" + raw).hexdigest()[:32]
    root.mkdir(parents=True, exist_ok=True)
    target = root / revision
    if assets_exist(root, revision):
        return revision
    # A partial existing revision is left intact for inspection. A new salted
    # revision can be generated by uploading a different image; never overwrite
    # files which a live browser could still be requesting.
    if target.exists():
        raise ImageValidationError("storage_error")
    staging = Path(tempfile.mkdtemp(prefix=".pending-", dir=root))
    try:
        square = _square(image, 512)
        square.save(staging / "icon.png", format="PNG")
        square.save(staging / "icon-512.png", format="PNG")
        _square(image, 192).save(staging / "icon-192.png", format="PNG")
        apple = _square(image, 180)
        apple_rgb = Image.new("RGB", (180, 180), "white")
        apple_rgb.paste(apple, mask=apple.getchannel("A"))
        apple_rgb.save(staging / "apple-touch-icon.png", format="PNG")
        square.save(
            staging / "favicon.ico",
            format="ICO",
            sizes=[(16, 16), (32, 32), (48, 48), (64, 64)],
        )
        os.replace(staging, target)
    except Exception:
        shutil.rmtree(staging, ignore_errors=True)
        raise
    finally:
        image.close()
    return revision
